export const OCCASION_BY_ID: Record<string, OccasionDef> = Object.fromEntries(OCCASIONS.map((o) => [o.id, o]));

export function getOccasion(id: string): OccasionDef {
  return OCCASION_BY_ID[id] ?? OCCASION_BY_ID.custom;
}

/** Case-insensitive search over names, taglines and keywords. */
export function searchOccasions(query: string): OccasionDef[] {
  const q = query.trim().toLowerCase();
  if (!q) return OCCASIONS;
  const terms = q.split(/\s+/);
  return OCCASIONS.filter((o) => {
    const hay = [o.name, o.tagline, ...o.keywords].join(' ').toLowerCase();
    return terms.every((t) => hay.includes(t));
  });
}

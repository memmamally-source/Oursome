/**
 * Generates src/components/ui/icons.generated.ts with only the Ionicons the
 * app uses (instead of shipping the whole 380 KB icon font).
 * Run after using a new icon name: `npm run icons`.
 * Icons: Ionicons (MIT) — https://ionic.io/ionicons
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const svgDir = path.join(root, 'node_modules/ionicons/dist/svg');
const available = new Set(fs.readdirSync(svgDir).map((f) => f.replace(/\.svg$/, '')));

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return e.name === '__tests__' ? [] : walk(p);
    return /\.(ts|tsx)$/.test(e.name) && !e.name.endsWith('.generated.ts') ? [p] : [];
  });

const used = new Set();
for (const file of walk(path.join(root, 'src'))) {
  for (const [, name] of fs.readFileSync(file, 'utf8').matchAll(/['"`]([a-z0-9-]+)['"`]/g)) {
    if (available.has(name)) used.add(name);
  }
}

const icons = {};
for (const name of [...used].sort()) {
  const svg = fs.readFileSync(path.join(svgDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>.*?<\/title>/g, '')
    .replace(/ class="[^"]*"/g, '');
  // Unstyled Ionicons shapes are filled with the current colour.
  icons[name] = inner.replace(/<(path|circle|rect|ellipse|polygon)(?![^>]*\bfill=)/g, '<$1 fill="currentColor"');
}

const out = `// Generated by scripts/generate-icons.js — do not edit by hand.
// Ionicons (MIT) — https://ionic.io/ionicons. ${Object.keys(icons).length} icons.
export const ICONS = ${JSON.stringify(icons, null, 1)} as const;
export type IconName = keyof typeof ICONS;
`;
fs.writeFileSync(path.join(root, 'src/components/ui/icons.generated.ts'), out);
console.log(`Generated ${Object.keys(icons).length} icons.`);
